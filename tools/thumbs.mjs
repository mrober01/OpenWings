// thumbs.mjs — pre-renders a small top-down picture of every map for the menu's MAP option
// (shown the instant you click, before the 3D backdrop is rebuilt).
//   node tools/thumbs.mjs   → src/ui/mapThumbs.js (GENERATED; needs python3 + Pillow for the JPEG step)
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { Heightfield } from '../src/world/Heightfield.js';
import { MAP_ORDER } from '../src/world/Maps.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const S = 96, out = {};
for (const key of MAP_ORDER) {
  const hf = new Heightfield(key), mc = hf.map.mini, step = hf.size / S, buf = Buffer.alloc(S * S * 3);
  for (let j = 0; j < S; j++) for (let i = 0; i < S; i++) {
    const x = (i + 0.5) * step - hf.half, z = (j + 0.5) * step - hf.half, h = hf.height(x, z);
    let c;
    if (h <= 0.2) { const k = Math.min(1, -h / 60); c = [24 - k * 12, 70 - k * 30, 104 - k * 36]; }
    else {
      const col = h < 4 ? mc.sand : h > mc.highH ? mc.high : h > mc.upH ? mc.up : mc.low, f = hf.forest(x, z, h);
      c = col === mc.low ? [col[0] - f * 30, col[1] - f * 30, col[2] - f * 22] : [...col];
      const u = hf.urbanGround(x, z) * 0.75;                           // built-up area (real cities)
      c = c.map((v, n) => v + ([150, 150, 156][n] - v) * u);
      const sh = 1 + Math.max(-0.45, Math.min(0.45, (h - hf.height(x + step, z) + h - hf.height(x, z + step)) / step * 1.3));
      c = c.map(v => v * sh);
    }
    if (hf.city && !hf.zones && Math.hypot(x - hf.city.x, z - hf.city.z) < hf.city.r) c = [170, 170, 176];
    buf.set(c.map(v => Math.max(0, Math.min(255, Math.round(v)))), (j * S + i) * 3);
  }
  for (const a of hf.airfields) for (let s = -1300; s <= 1300; s += 100) {   // runways as light strokes
    const i = Math.round((a.x + a.dirX * s + hf.half) / step), j = Math.round((a.z + a.dirZ * s + hf.half) / step);
    if (i >= 0 && j >= 0 && i < S && j < S) buf.set([235, 235, 225], (j * S + i) * 3);
  }
  const ppm = `/tmp/ow-thumb-${key}.ppm`;
  fs.writeFileSync(ppm, Buffer.concat([Buffer.from(`P6 ${S} ${S} 255\n`), buf]));
  out[key] = execFileSync('python3', ['-I', '-c',
    'import sys,io,base64\nfrom PIL import Image\nb=io.BytesIO(); Image.open(sys.argv[1]).save(b,"JPEG",quality=72); print(base64.b64encode(b.getvalue()).decode())', ppm]).toString().trim();
  console.log(key, out[key].length, 'chars');
}
fs.writeFileSync(path.join(ROOT, 'src/ui/mapThumbs.js'), `// GENERATED by tools/thumbs.mjs — do not edit. ${S}px top-down JPEGs of each map for the menu.
export const MAP_THUMBS = {
${Object.entries(out).map(([k, v]) => `  ${k}: 'data:image/jpeg;base64,${v}',`).join('\n')}
};
`);
